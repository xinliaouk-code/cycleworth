// 地球半径（公里）
const EARTH_RADIUS_KM = 6371

/**
 * 计算两个经纬度点之间的球面距离（Haversine 公式），单位：公里。
 * 相比平面欧氏距离，在伦敦所在的高纬度地区不会因经度压缩而失准。
 */
export function haversineDistance(
  lat1: number,
  lng1: number,
  lat2: number,
  lng2: number
): number {
  const toRad = (deg: number) => (deg * Math.PI) / 180
  const dLat = toRad(lat2 - lat1)
  const dLng = toRad(lng2 - lng1)

  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2

  return 2 * EARTH_RADIUS_KM * Math.asin(Math.sqrt(a))
}

/** 用 Haversine 球面距离取最近的站点（站点匹配更精准）。无坐标时返回 '未知起点'。 */
export function getNearestStation(lat?: number, lng?: number): string {
  if (lat == null || lng == null) return '未知起点'
  let nearest = TUBE_STATIONS[0]
  let minDistance = Infinity

  for (const station of TUBE_STATIONS) {
    const dist = haversineDistance(lat, lng, station.lat, station.lng)
    if (dist < minDistance) {
      minDistance = dist
      nearest = station
    }
  }
  return nearest.name
}
